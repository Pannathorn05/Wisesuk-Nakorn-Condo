-- กฎความเป็นเจ้าของ: 1 สาขามีผู้ดูแล 1 คน และทั้งระบบมีหัวหน้าผู้ดูแลคนเดียว
--
-- ของเดิมที่ 0001 บังคับไว้แค่ทิศเดียว — CHECK admin_requires_branch บอกว่า
-- "admin ต้องมี 1 สาขา" แต่ไม่ได้ห้ามสองคนถือสาขาเดียวกัน และไม่ได้ห้ามมี
-- หัวหน้าผู้ดูแลหลายคน migration นี้ปิดช่องที่เหลือทั้งสองช่อง
--
-- ใช้ partial unique index แทน constraint เพราะเงื่อนไขมีผลเฉพาะบาง role
-- ส่วน UNIQUE ธรรมดาจะไปบังคับกับ member ทุกคนที่ branch_id เป็น NULL ด้วย

-- หนึ่งสาขามีผู้ดูแลได้คนเดียว
-- (แถวที่ role ไม่ใช่ admin ไม่เข้า index จึงไม่ถูกกระทบ)
CREATE UNIQUE INDEX uq_admin_per_branch
    ON users (branch_id)
    WHERE role = 'admin';

-- ทั้งระบบมีหัวหน้าผู้ดูแลได้คนเดียว
--
-- index บนคอลัมน์ role ที่กรองเฉพาะ superadmin ทำให้มีได้แถวเดียวโดยปริยาย
-- ถ้าวันหนึ่งต้องการย้ายตัวหัวหน้าผู้ดูแล ต้องลบ/ลดสิทธิ์คนเดิมก่อนแล้วค่อยตั้งคนใหม่
-- ซึ่งเป็นพฤติกรรมที่ต้องการ — ไม่ควรมีจังหวะที่ระบบมีหัวหน้าผู้ดูแลสองคนพร้อมกัน
CREATE UNIQUE INDEX uq_single_superadmin
    ON users (role)
    WHERE role = 'superadmin';
